// ── Helper: translate a key in the current language, falling back to English ──
function t(key) {
  const lang = (typeof _currentLang !== "undefined" && _currentLang) ? _currentLang : "EN";
  const dict = I18N[lang] || I18N.EN;
  return (dict[key] !== undefined) ? dict[key] : (I18N.EN[key] !== undefined ? I18N.EN[key] : key);
}

// ── Core: apply the active language to the whole page ──────────────────────────
//   Walks every element with data-i18n / data-i18n-ph / data-i18n-html and swaps text.
function applyLanguage(lang) {
  if (!I18N[lang]) lang = "EN";
  if (typeof _currentLang !== "undefined") _currentLang = lang;
  try { localStorage.setItem("jyotish-lang", lang); } catch (e) {}

  // Text content
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = t(key);
    if (val !== undefined) el.textContent = val;
  });

  // Placeholder attributes (for inputs)
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.getAttribute("data-i18n-ph");
    const val = t(key);
    if (val !== undefined) el.setAttribute("placeholder", val);
  });

  // HTML content (for strings that contain a <strong> label etc.)
  document.querySelectorAll("[data-i18n-html]").forEach(el => {
    const key = el.getAttribute("data-i18n-html");
    const val = t(key);
    if (val !== undefined) el.innerHTML = val;
  });

  // Update the <html lang="..."> attribute for accessibility / SEO
  const htmlLangMap = { EN:"en", TA:"ta", TE:"te", HI:"hi", KA:"kn", ML:"ml" };
  document.documentElement.setAttribute("lang", htmlLangMap[lang] || "en");

  // Reflect active state on any language buttons
  document.querySelectorAll("[data-setlang]").forEach(btn => {
    btn.classList.toggle("active", btn.getAttribute("data-setlang") === lang);
  });
}

// Expose globally so app.js and inline handlers can use them
if (typeof window !== "undefined") {
  window.I18N = I18N;
  window.LANG_META = LANG_META;
  window.LANG_AI_NAME = LANG_AI_NAME;
  window.t = t;
  window.applyLanguage = applyLanguage;
}
